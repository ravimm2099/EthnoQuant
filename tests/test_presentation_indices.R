source('R_ethnoquant.R')
x<-data.frame(informant=c('a','a','b','b','b'),species=c('X','Y','X','X','Y'))
e<-eq_species_evenness(x)
stopifnot(abs(e$overall$SEtot-((1/((3/5)^2+(2/5)^2))/2))<1e-10)
stopifnot(abs(e$per_informant$SEi[e$per_informant$informant=='a']-1)<1e-10)
y<-data.frame(species=c('X','X','Y'),use=c('a','b','a'),quality=c(2,3,1),intensity=c(2,2,1),exclusivity=c(1,2,1))
z<-eq_ics_scores(y);stopifnot(z$ICS[z$species=='X']==16)
stopifnot(inherits(try(eq_ics_scores(transform(y,quality=c(NA,3,1))),silent=TRUE),'try-error'))
cat('Equitability and ICS test assertions passed\n')
